"""Build the submission archive: regenerate the transcript index, then zip the project (standard library only).

The archive lands in a `dist/` folder next to the project folder, with `ecommerce-support-agent/` as its root.
"""

import logging
import sys
import zipfile
from collections.abc import Iterator
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DIST_DIR = PROJECT_ROOT.parent / "dist"
ARCHIVE_PATH = DIST_DIR / f"{PROJECT_ROOT.name}.zip"
TRANSCRIPTS_DIR = PROJECT_ROOT / "claude-transcripts"
INDEX_PATH = TRANSCRIPTS_DIR / "INDEX.md"
SESSION_SUFFIX = ".jsonl"

INCLUDED_DIRECTORIES = ("src", "tests", "scripts", "mock_env", "data", "config", "docs", "claude-transcripts", ".git")
INCLUDED_FILES = (
    "README.md",
    "pyproject.toml",
    "requirements.txt",
    "requirements-dev.txt",
    ".pre-commit-config.yaml",
    ".gitattributes",
    ".gitignore",
    ".env.example",
)
EXCLUDED_PARTS = frozenset(
    {
        ".git",
        ".venv",
        "__pycache__",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        ".import_linter_cache",
        "htmlcov",
    }
)
EXCLUDED_NAMES = frozenset({".env", ".coverage", "settings.local.json"})
EXCLUDED_SUFFIXES = frozenset({".zip", ".pyc"})
EXCLUDED_PART_SUFFIX = ".egg-info"

logger = logging.getLogger("package")


def is_excluded(relative: Path) -> bool:
    if EXCLUDED_PARTS & set(relative.parts) or any(part.endswith(EXCLUDED_PART_SUFFIX) for part in relative.parts):
        return True
    return relative.name in EXCLUDED_NAMES or relative.suffix in EXCLUDED_SUFFIXES


def files_to_archive(root: Path = PROJECT_ROOT) -> Iterator[Path]:
    for directory in INCLUDED_DIRECTORIES:
        for path in sorted((root / directory).rglob("*")):
            if path.is_file() and not is_excluded(path.relative_to(root)):
                yield path
    yield from (root / name for name in INCLUDED_FILES if (root / name).is_file())


def _index_rows(transcripts: Path) -> Iterator[str]:
    for session in sorted(transcripts.glob(f"*{SESSION_SUFFIX}")):
        session_id = session.stem
        yield f"| {session_id} | {session.name} | {session.stat().st_size} |"
        companion = transcripts / session_id
        for path in sorted(companion.rglob("*")) if companion.is_dir() else ():
            if path.is_file():
                yield f"| {session_id} | {path.relative_to(transcripts).as_posix()} | {path.stat().st_size} |"


def write_index(transcripts: Path = TRANSCRIPTS_DIR) -> int:
    """Rebuild INDEX.md from the session files actually present; returns the number of files listed."""
    rows = list(_index_rows(transcripts))
    header = [
        "# Claude Code transcripts",
        "",
        "Claude Code session files for this project directory, copied from",
        "`%USERPROFILE%\\.claude\\projects\\D--WorkEnv-ecommerce-support-agent\\`. Generated by `scripts/package.py`.",
        "",
        "| session ID | file | bytes |",
        "|---|---|---|",
    ]
    (transcripts / INDEX_PATH.name).write_text("\n".join([*header, *rows]) + "\n", encoding="utf-8")
    return len(rows)


def build_archive(archive: Path = ARCHIVE_PATH, root: Path = PROJECT_ROOT) -> list[str]:
    archive.parent.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for path in files_to_archive(root):
            name = f"{root.name}/{path.relative_to(root).as_posix()}"
            bundle.write(path, name)
            names.append(name)
    return names


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)
    logger.info("transcript index: %d files listed in %s", write_index(), INDEX_PATH.relative_to(PROJECT_ROOT))
    build_archive()
    with zipfile.ZipFile(ARCHIVE_PATH) as bundle:
        for info in bundle.infolist():
            logger.info("%10d  %s", info.file_size, info.filename)
        logger.info(
            "%d files, %d bytes compressed -> %s", len(bundle.infolist()), ARCHIVE_PATH.stat().st_size, ARCHIVE_PATH
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
